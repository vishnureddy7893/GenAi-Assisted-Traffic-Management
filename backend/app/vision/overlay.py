"""Annotated preview rendering.

The overlay is generated by **this application**, not by the detector library.
That matters for two reasons: the drawing stays consistent whichever backend
produced the boxes, and what the operator sees is rendered from the same
:class:`~app.vision.detector.Detection` records the API returns — so the picture
and the numbers cannot disagree.

Colour encodes road-user class, and only that. It carries no severity, no risk
and no traffic meaning, because none of those exist yet.
"""

from __future__ import annotations

from typing import Any

from app.core.errors import DataSourceError
from app.domain.enums import VehicleClass
from app.vision.detector import Detection
from app.vision.quality import AssessedDetection
from app.vision.tracker import Track

#: Class colours in RGB. Chosen to stay distinguishable in both light and dark
#: surroundings and for the most common confusion pair (car/truck) to be far
#: apart in hue rather than merely in brightness.
CLASS_COLOURS: dict[VehicleClass, tuple[int, int, int]] = {
    VehicleClass.CAR: (56, 176, 255),
    VehicleClass.TRUCK: (255, 140, 66),
    VehicleClass.BUS: (255, 214, 61),
    VehicleClass.MOTORCYCLE: (168, 130, 255),
    VehicleClass.BICYCLE: (94, 224, 168),
    VehicleClass.PERSON: (255, 99, 132),
}
_DEFAULT_COLOUR = (180, 190, 205)


def colour_for(vehicle_class: VehicleClass) -> tuple[int, int, int]:
    """RGB colour for a road-user class."""
    return CLASS_COLOURS.get(vehicle_class, _DEFAULT_COLOUR)


def _dashed_rectangle(
    cv2: Any,
    canvas: Any,
    top_left: tuple[int, int],
    bottom_right: tuple[int, int],
    colour: tuple[int, int, int],
    thickness: int,
    dash: int = 6,
) -> None:
    """Draw a dashed rectangle, for a box that will not be counted.

    Dashes rather than a different colour: colour already encodes road-user
    class here, and overloading it would make "uncountable truck" and "confirmed
    bus" compete for the same visual channel.
    """
    x1, y1 = top_left
    x2, y2 = bottom_right
    for x in range(x1, x2, dash * 2):
        end = min(x + dash, x2)
        cv2.line(canvas, (x, y1), (end, y1), colour, thickness)
        cv2.line(canvas, (x, y2), (end, y2), colour, thickness)
    for y in range(y1, y2, dash * 2):
        end = min(y + dash, y2)
        cv2.line(canvas, (x1, y), (x1, end), colour, thickness)
        cv2.line(canvas, (x2, y), (x2, end), colour, thickness)


def render_overlay(
    frame: Any,
    detections: tuple[Detection, ...] | tuple[AssessedDetection, ...],
    *,
    tracks: tuple[Track, ...] = (),
    show_confidence: bool = True,
) -> Any:
    """Draw boxes and labels onto a copy of an RGB frame.

    The input frame is never modified: it is the raw ingested pixel data, and a
    later stage may need it unannotated.

    When ``tracks`` are supplied, each box is labelled with its track id, which
    is what lets a reader verify visually that an id stays attached to the same
    vehicle across frames.

    Accepts either raw detections or assessed ones. Given assessments, a box
    that will not be counted is drawn **dashed and unfilled** and its label says
    why. That distinction is the whole point of drawing it: a rejected box
    rendered identically to a confirmed one turns the overlay into evidence for
    a count that does not include it, and an operator comparing the picture to
    the number would be right to conclude the number is wrong.
    """
    try:
        import cv2
        import numpy as np
    except ImportError as exc:  # pragma: no cover - dependency-gated
        msg = "Overlay rendering requires OpenCV and numpy."
        raise DataSourceError(msg, missing_dependency=str(exc)) from exc

    canvas = np.ascontiguousarray(frame.copy())
    height, width = canvas.shape[0], canvas.shape[1]

    # Scale line and text with resolution so a 4K frame is not annotated with
    # hairlines and a 320px thumbnail is not covered by its own labels.
    scale = max(min(width, height) / 640.0, 0.35)
    thickness = max(1, round(2 * scale))
    font_scale = 0.45 * scale
    font = cv2.FONT_HERSHEY_SIMPLEX

    track_by_box: dict[tuple[int, int, int, int], int] = {}
    for track in tracks:
        if not track.history:
            continue
        box = track.current.bbox
        key = (int(box.x1), int(box.y1), int(box.x2), int(box.y2))
        track_by_box[key] = track.track_id

    for item in detections:
        assessed = item if isinstance(item, AssessedDetection) else None
        detection = assessed.detection if assessed is not None else item
        confirmed = assessed is None or assessed.is_confirmed

        box = detection.bbox
        colour = colour_for(detection.vehicle_class)
        x1, y1 = int(box.x1), int(box.y1)
        x2, y2 = int(box.x2), int(box.y2)

        if confirmed:
            cv2.rectangle(canvas, (x1, y1), (x2, y2), colour, thickness)
        else:
            _dashed_rectangle(cv2, canvas, (x1, y1), (x2, y2), colour, thickness)

        parts = [detection.vehicle_class.value]
        track_id = track_by_box.get((x1, y1, x2, y2))
        if track_id is not None:
            parts.insert(0, f"#{track_id}")
        if show_confidence:
            parts.append(f"{detection.confidence:.2f}")
        if assessed is not None and not confirmed:
            parts.append(f"[{assessed.quality.value}]")
        label = " ".join(parts)

        (text_w, text_h), baseline = cv2.getTextSize(label, font, font_scale, 1)
        # Place the label inside the frame when the box is at the top edge,
        # otherwise it is drawn off-canvas and silently lost.
        label_top = y1 - text_h - baseline
        if label_top < 0:
            label_top = min(y2, height - text_h - baseline - 1)
        label_top = max(0, label_top)
        label_left = max(0, min(x1, width - text_w - 1))

        cv2.rectangle(
            canvas,
            (label_left, label_top),
            (label_left + text_w + 4, label_top + text_h + baseline),
            colour,
            -1,
        )
        cv2.putText(
            canvas,
            label,
            (label_left + 2, label_top + text_h),
            font,
            font_scale,
            (16, 20, 28),
            1,
            cv2.LINE_AA,
        )

    return canvas


def encode_png(frame: Any) -> bytes:
    """Encode an RGB frame as PNG bytes.

    PNG rather than JPEG: the overlay contains thin lines and small text, and
    JPEG artefacts around high-contrast edges make box boundaries ambiguous
    exactly where the reader is trying to judge them.
    """
    try:
        import cv2
    except ImportError as exc:  # pragma: no cover - dependency-gated
        msg = "Encoding requires OpenCV."
        raise DataSourceError(msg, missing_dependency=str(exc)) from exc

    # cv2 encodes BGR; our frames are RGB.
    bgr = cv2.cvtColor(frame, cv2.COLOR_RGB2BGR)
    ok, buffer = cv2.imencode(".png", bgr)
    if not ok:
        msg = "Failed to encode the annotated frame."
        raise DataSourceError(msg)
    return bytes(buffer.tobytes())
