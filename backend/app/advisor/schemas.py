"""The advisory the system will show an operator, and how it was produced.

One shape for both modes
------------------------
An LLM-written advisory and a deterministic one have the same structure, so a
panel renders one code path and a reader compares like with like. What they do
not share is the claim about where the words came from: :attr:`AdvisoryMode`
is mandatory, and the deterministic path never labels itself ``llm``. Dressing
template text up as a model's reasoning would be the same class of lie the fact
table exists to prevent, one level up.
"""

from __future__ import annotations

import datetime as dt
from enum import StrEnum
from typing import Annotated

from pydantic import Field, model_validator

from app.domain.base import DomainModel
from app.domain.decision import NarrativeValidation


class AdvisoryMode(StrEnum):
    """How the advisory text was produced."""

    LLM = "llm"
    """Generated by the configured language model and validated against the
    fact table."""

    DETERMINISTIC_FALLBACK = "deterministic_fallback"
    """Composed from the facts by fixed rules. Used when no provider is
    configured, when the provider fails, and when a generated advisory is
    rejected by validation -- a rejected narrative is never shown."""


class TrafficAdvisory(DomainModel):
    """Advisory guidance over one observation area's facts. Advisory only."""

    mode: AdvisoryMode
    observation_area_id: Annotated[str, Field(min_length=1, max_length=120)]

    summary: Annotated[str, Field(min_length=1, max_length=1500)]
    traffic_assessment: Annotated[str, Field(min_length=1, max_length=1500)]
    suggestions: tuple[Annotated[str, Field(min_length=1, max_length=600)], ...] = ()
    safety_considerations: tuple[
        Annotated[str, Field(min_length=1, max_length=600)], ...
    ] = ()

    route_advice: Annotated[str, Field(min_length=1, max_length=1000)]
    """Never names a route as better without a route comparison in the facts.
    Without one it says an alternative should be evaluated, which is a request
    for evidence rather than a claim about it."""

    limitations: tuple[Annotated[str, Field(min_length=1, max_length=600)], ...] = ()
    """What this advisory could not see. Populated from the recorded absences,
    so a gap in the evidence reaches the operator rather than stopping here."""

    evidence_ids: tuple[Annotated[str, Field(max_length=64)], ...] = ()
    """Fact ids the advisory rests on. Every one is checked against the fact
    table; an id the table does not contain is not rendered."""

    model_id: Annotated[str, Field(max_length=200)] | None = None
    """The model that wrote it, when one did. ``None`` in fallback mode: naming
    a model that was never called would misattribute the text."""

    generated_at: dt.datetime
    validation: NarrativeValidation | None = None
    """Result of scanning generated prose for numbers the facts do not support.
    ``None`` in fallback mode, where the prose is built from the facts and has
    nothing to validate against itself."""

    advisory_only: bool = True
    """Fixed. This system recommends to human operators and controls nothing."""

    @model_validator(mode="after")
    def _stays_advisory_and_honest(self) -> TrafficAdvisory:
        if not self.advisory_only:
            msg = (
                "TrafficAdvisory.advisory_only cannot be False: the advisor "
                "issues recommendations to human operators and has no control "
                "path to any signal, vehicle or piece of infrastructure"
            )
            raise ValueError(msg)
        if self.mode is AdvisoryMode.DETERMINISTIC_FALLBACK and self.model_id:
            msg = (
                "a deterministic fallback advisory must not name a model: the "
                "text was composed from the facts by fixed rules and attributing "
                "it to a model that was never called is a fabricated provenance"
            )
            raise ValueError(msg)
        if self.mode is AdvisoryMode.LLM and not self.model_id:
            msg = "an LLM advisory must name the model that produced it"
            raise ValueError(msg)
        return self
